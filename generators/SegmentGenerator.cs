using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;
using Patice.Domain;
using Patice.Segments;

namespace Patice.Generators;

[Generator]
public sealed class SegmentGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor InvalidSegments = new(
        "PATICE001", "Invalid segment data", "{0}: {1}", "Segments",
        DiagnosticSeverity.Error, isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var files = context.AdditionalTextsProvider
            .Where(file => file.Path.EndsWith(".json", StringComparison.OrdinalIgnoreCase))
            .Select((file, cancellation) => (file.Path, Text: file.GetText(cancellation).ToString()))
            .Collect();
        context.RegisterSourceOutput(files, Generate);
    }

    private static void Generate(SourceProductionContext context, ImmutableArray<(string Path, string Text)> files)
    {
        var segments = new List<Segment>();
        var ids = new HashSet<(int, Difficulty, Guid)>();
        foreach (var file in files.OrderBy(file => file.Path, StringComparer.Ordinal))
        {
            try
            {
                using var stream = new MemoryStream(Encoding.UTF8.GetBytes(file.Text));
                var entries = SegmentStorage.ReadSegments(stream);
                SegmentStorage.ValidateSegments(entries);
                foreach (var entry in entries)
                {
                    if (entry.musicId <= 0 || !Enum.IsDefined(typeof(Difficulty), entry.difficulty))
                        throw new InvalidDataException("Invalid chart ID or difficulty.");
                    if (!ids.Add((entry.musicId, entry.difficulty, entry.id)))
                        throw new InvalidDataException("Duplicate segment identity.");
                }
                segments.AddRange(entries);
            }
            catch (Exception error)
            {
                context.ReportDiagnostic(Diagnostic.Create(InvalidSegments, Location.None, file.Path, error.Message));
                return;
            }
        }

        var source = new StringBuilder("""
            // <auto-generated />
            using System;
            using System.Collections.Generic;
            using Patice.Domain;
            namespace Patice.Segments;
            public sealed partial class BuiltinSegments
            {
                private static partial Dictionary<int, Dictionary<Difficulty, Segment[]>> CreateCharts() => new()
                {
            """);
        foreach (var chart in segments.GroupBy(segment => segment.musicId))
        {
            source.AppendLine($"[{chart.Key}] = new() {{");
            foreach (var level in chart.GroupBy(segment => segment.difficulty))
            {
                source.AppendLine($"[Difficulty.{level.Key}] = new Segment[] {{");
                foreach (var segment in level)
                {
                    var bytes = segment.id.ToByteArray();
                    var guid = new[] { (int)BitConverter.ToInt32(bytes, 0), BitConverter.ToInt16(bytes, 4), BitConverter.ToInt16(bytes, 6) }
                        .Concat(bytes.Skip(8).Select(value => (int)value));
                    source.AppendLine(FormattableString.Invariant(
                        $"new Segment({segment.musicId}, Difficulty.{segment.difficulty}, new Guid({string.Join(", ", guid.Select(value => value.ToString(CultureInfo.InvariantCulture)))}), {SymbolDisplay.FormatLiteral(segment.name, true)}, {segment.startMs}, {segment.endMs}),"));
                }
                source.AppendLine("},");
            }
            source.AppendLine("},");
        }
        source.AppendLine("}; }");
        context.AddSource("BuiltinSegments.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
    }
}
